CREATE TABLE t_user (
                        user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                        name VARCHAR(100) NOT NULL,
                        email VARCHAR(150) NOT NULL UNIQUE,
                        password_hash VARCHAR(100) NOT NULL,
                        role VARCHAR(10) NOT NULL CHECK (role IN ('CIDADAO', 'GESTOR')),
                        neighborhood VARCHAR(80),
                        active BOOLEAN NOT NULL DEFAULT TRUE,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_category (
                            category_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                            name VARCHAR(60) NOT NULL UNIQUE,
                            description VARCHAR(255),
                            base_weight SMALLINT NOT NULL CHECK (base_weight BETWEEN 1 AND 5),
                            active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE t_incident (
                            incident_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                            user_id BIGINT NOT NULL REFERENCES t_user(user_id),
                            category_id BIGINT NOT NULL REFERENCES t_category(category_id),
                            title VARCHAR(120) NOT NULL,
                            description VARCHAR(1000) NOT NULL,
                            address VARCHAR(200) NOT NULL,
                            neighborhood VARCHAR(80) NOT NULL,
                            latitude NUMERIC(9,6),
                            longitude NUMERIC(9,6),
                            status VARCHAR(15) NOT NULL DEFAULT 'OPEN'
                                CHECK (status IN ('OPEN','IN_REVIEW','IN_PROGRESS','RESOLVED','REJECTED','CANCELLED')),
                            urgency VARCHAR(10)
                                CHECK (urgency IN ('LOW','MEDIUM','HIGH','CRITICAL')),
                            ai_summary VARCHAR(300),
                            ai_guidance VARCHAR(600),
                            triage_status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                                CHECK (triage_status IN ('PENDING','DONE','FAILED')),
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            resolved_at TIMESTAMPTZ,
                            CONSTRAINT ck_incident_resolved CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);

CREATE TABLE t_incident_update (
                                   update_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                                   incident_id BIGINT NOT NULL REFERENCES t_incident(incident_id) ON DELETE CASCADE,
                                   user_id BIGINT NOT NULL REFERENCES t_user(user_id),
                                   previous_status VARCHAR(15) NOT NULL
                                       CHECK (previous_status IN ('OPEN','IN_REVIEW','IN_PROGRESS','RESOLVED','REJECTED','CANCELLED')),
                                   new_status VARCHAR(15) NOT NULL
                                       CHECK (new_status IN ('OPEN','IN_REVIEW','IN_PROGRESS','RESOLVED','REJECTED','CANCELLED')),
                                   note VARCHAR(500),
                                   created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_endorsement (
                               endorsement_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                               incident_id BIGINT NOT NULL REFERENCES t_incident(incident_id) ON DELETE CASCADE,
                               user_id BIGINT NOT NULL REFERENCES t_user(user_id),
                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               CONSTRAINT uq_endorsement UNIQUE (incident_id, user_id)
);

-- Auditoria: modelo equivalente ao Oracle; os registros serão feitos pelo Java
-- ou por gatilho PostgreSQL específico (AINDA NÃO IMPLEMENTADO NESTE PACOTE).
CREATE TABLE t_incident_audit (
                                  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                                  incident_id BIGINT NOT NULL,
                                  operation VARCHAR(6) NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
                                  changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  db_user VARCHAR(128) NOT NULL,
                                  old_status VARCHAR(15),
                                  new_status VARCHAR(15),
                                  old_values TEXT,
                                  new_values TEXT
);

CREATE INDEX ix_incident_user ON t_incident(user_id);
CREATE INDEX ix_incident_category ON t_incident(category_id);
CREATE INDEX ix_incident_nb_status ON t_incident(neighborhood, status);
CREATE INDEX ix_update_incident ON t_incident_update(incident_id);
CREATE INDEX ix_endorsement_user ON t_endorsement(user_id);
CREATE INDEX ix_audit_incident ON t_incident_audit(incident_id);
